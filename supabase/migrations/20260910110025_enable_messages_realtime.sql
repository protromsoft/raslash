-- Chat subscriptions use postgres_changes on public.messages. Publication
-- membership is independent from RLS, so keep the existing policies and make
-- only this table available to Supabase Realtime.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end
$$;
